% 第一问求解代码
% 运行后的结果为：
% 在95%信度下，允许误差为 0.01 时，所需的最小样本量为: 2436
% 在90%信度下，允许误差为 0.01 时，所需的最小样本量为: 1475
% 
% 在95%信度下，允许误差为 0.02 时，所需的最小样本量为: 609
% 在90%信度下，允许误差为 0.02 时，所需的最小样本量为: 369
% 
% 在95%信度下，允许误差为 0.03 时，所需的最小样本量为: 271
% 在90%信度下，允许误差为 0.03 时，所需的最小样本量为: 164
% 
% 在95%信度下，允许误差为 0.04 时，所需的最小样本量为: 153
% 在90%信度下，允许误差为 0.04 时，所需的最小样本量为: 93
% 
% 在95%信度下，允许误差为 0.05 时，所需的最小样本量为: 98
% 在90%信度下，允许误差为 0.05 时，所需的最小样本量为: 59

clc;
clear;

% 输入参数
p0 = 0.10;  % 标称次品率
epsilon_range = 0.01:0.01:0.05;  % 允许误差范围

% Z 值（正态分布临界值对应 95% 和 90% 的信度）
Z_95 = 1.645;  % 对应 95% 信度的 Z 值
Z_90 = 1.28;   % 对应 90% 信度的 Z 值

% 初始化结果数组
results_95 = zeros(size(epsilon_range));
results_90 = zeros(size(epsilon_range));

% 遍历不同的允许误差
for i = 1:length(epsilon_range)
    epsilon = epsilon_range(i);
    
    % 样本量计算公式
    n_95 = (Z_95^2 * p0 * (1 - p0)) / (epsilon^2);
    n_90 = (Z_90^2 * p0 * (1 - p0)) / (epsilon^2);
    
    % 向上取整，确保样本量为整数
    n_95 = ceil(n_95);
    n_90 = ceil(n_90);
    
    % 存储结果
    results_95(i) = n_95;
    results_90(i) = n_90;
end

% 输出结果
for i = 1:length(epsilon_range)
    fprintf('在95%%信度下，允许误差为 %.2f 时，所需的最小样本量为: %d\n', epsilon_range(i), results_95(i));
    fprintf('在90%%信度下，允许误差为 %.2f 时，所需的最小样本量为: %d\n', epsilon_range(i), results_90(i));
    fprintf('\n')
end